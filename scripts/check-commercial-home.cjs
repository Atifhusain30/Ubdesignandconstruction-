const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve } = require('node:path')
const out = resolve(__dirname, '../out')
const html = readFileSync(resolve(out, 'index.html'), 'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '').replace(/<!--\s*-->/g, '')
assert.match(html, /<h1>Commercial design<br[^>]*\/> &amp; construction\.<\/h1>/, 'commercial headline')
const hero = html.match(/<section class="hero">([\s\S]*?)<\/section>/)?.[1]
assert.ok(hero, 'hero exists')
assert.doesNotMatch(hero, /<img|<picture|<svg/, 'hero is photo and illustration free')
assert.match(hero, /href="\/contact\/"[^>]*>Discuss your project/)
assert.match(html, /href="\/gallery\/"[^>]*>View all projects/)
for (const id of ['main', 'services', 'work', 'design', 'commercial', 'millwork', 'contact']) assert.ok(html.includes(`id="${id}"`), `missing anchor: ${id}`)
assert.match(html, /rel="canonical" href="https:\/\/ubconstructionanddesign\.com\/"/)
assert.match(readFileSync(resolve(out, 'contact/index.html'), 'utf8'), /data-netlify="true"/)
assert.match(readFileSync(resolve(out, 'sitemap.xml'), 'utf8'), /https:\/\/ubconstructionanddesign\.com\/gallery\//)
console.log('Commercial homepage, contact markup, and sitemap checks passed.')
